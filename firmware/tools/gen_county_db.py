#!/usr/bin/env python3
"""Generate firmware/src/app/county_db.h from tools/ne_cache/us_counties.geojson.

Census county outlines for all 50 states, grouped per state in the order of
kCountyStateAbbr (AL=0 ... WY=49). Coordinates are degrees * 50 (int16), same as map_db.h.
Run:  python firmware/tools/gen_county_db.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "ne_cache", "us_counties.geojson")
OUT = os.path.join(HERE, "..", "src", "app", "county_db.h")

# (abbr, state FIPS) alphabetical by state name.
STATES = [
    ("AL", "01"), ("AK", "02"), ("AZ", "04"), ("AR", "05"), ("CA", "06"), ("CO", "08"), ("CT", "09"),
    ("DE", "10"), ("FL", "12"), ("GA", "13"), ("HI", "15"), ("ID", "16"), ("IL", "17"), ("IN", "18"),
    ("IA", "19"), ("KS", "20"), ("KY", "21"), ("LA", "22"), ("ME", "23"), ("MD", "24"), ("MA", "25"),
    ("MI", "26"), ("MN", "27"), ("MS", "28"), ("MO", "29"), ("MT", "30"), ("NE", "31"), ("NV", "32"),
    ("NH", "33"), ("NJ", "34"), ("NM", "35"), ("NY", "36"), ("NC", "37"), ("ND", "38"), ("OH", "39"),
    ("OK", "40"), ("OR", "41"), ("PA", "42"), ("RI", "44"), ("SC", "45"), ("SD", "46"), ("TN", "47"),
    ("TX", "48"), ("UT", "49"), ("VT", "50"), ("VA", "51"), ("WA", "53"), ("WV", "54"), ("WI", "55"),
    ("WY", "56"),
]


def rings(geom):
    t = geom["type"]
    if t == "Polygon":
        for r in geom["coordinates"]:
            yield r
    elif t == "MultiPolygon":
        for poly in geom["coordinates"]:
            for r in poly:
                yield r


def q(v):
    return int(round(v * 50.0))


def main():
    with open(SRC, encoding="utf-8") as f:
        gj = json.load(f)
    by_state = {fips: [] for _, fips in STATES}
    for feat in gj["features"]:
        st = feat["properties"].get("STATE")
        if st in by_state:
            by_state[st].append(feat["geometry"])

    pts = []
    polys = []  # (start, count)
    ranges = []  # (poly_start, poly_count)
    for abbr, fips in STATES:
        p0 = len(polys)
        for geom in by_state[fips]:
            for ring in rings(geom):
                start = len(pts)
                prev = None
                n = 0
                for c in ring:
                    lat_q, lon_q = q(c[1]), q(c[0])
                    lat_q = max(-4500, min(4500, lat_q))
                    lon_q = max(-9000, min(9000, lon_q))
                    if (lat_q, lon_q) == prev:
                        continue
                    pts.append((lat_q, lon_q))
                    prev = (lat_q, lon_q)
                    n += 1
                if n >= 3:
                    polys.append((start, n))
                else:
                    del pts[start:]
        ranges.append((p0, len(polys) - p0))

    out = []
    out.append("#pragma once")
    out.append("#include <stdint.h>")
    out.append("// Auto-generated by firmware/tools/gen_county_db.py from Census county outlines.")
    out.append("// lat_q/lon_q = degrees * 50. Counties grouped per state in kCountyStateAbbr order.")
    out.append("struct CountyPt { int16_t lat_q; int16_t lon_q; };")
    out.append("struct CountyPoly { uint32_t start; uint16_t count; };")
    out.append("struct CountyStateRange { uint16_t poly_start; uint16_t poly_count; };")
    out.append("static const char *const kCountyStateAbbr[50] = {")
    out.append("  " + ", ".join('"%s"' % a for a, _ in STATES))
    out.append("};")
    out.append("static const CountyPt kCountyPts[] = {")
    line = []
    for i, (la, lo) in enumerate(pts):
        line.append("{%d,%d}" % (la, lo))
        if len(line) == 12:
            out.append("  " + ",".join(line) + ",")
            line = []
    if line:
        out.append("  " + ",".join(line) + ",")
    out.append("};")
    out.append("static const uint32_t kCountyPtCount = %d;" % len(pts))
    out.append("static const CountyPoly kCountyPolys[] = {")
    line = []
    for (s, n) in polys:
        line.append("{%d,%d}" % (s, n))
        if len(line) == 10:
            out.append("  " + ",".join(line) + ",")
            line = []
    if line:
        out.append("  " + ",".join(line) + ",")
    out.append("};")
    out.append("static const uint16_t kCountyPolyCount = %d;" % len(polys))
    out.append("static const CountyStateRange kCountyStateRanges[50] = {")
    out.append("  " + ", ".join("{%d,%d}" % r for r in ranges))
    out.append("};")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", OUT, "pts", len(pts), "polys", len(polys), "bytes", os.path.getsize(OUT))


if __name__ == "__main__":
    main()
